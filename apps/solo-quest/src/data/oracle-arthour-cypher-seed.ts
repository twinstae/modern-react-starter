const cypherList = (letter: string, cyphers: CypherEntry[]): Oracle => ({
  id: `arthour-cypher-list-${letter.toLowerCase()}`,
  name: `아서투르 경 사이퍼 목록 ${letter}`,
  category: "사이퍼 시스템",
  group: "사이퍼",
  sides: 100,
  kind: "single",
  description: `목록 ${letter}. ${ORACLE_DESCRIPTION}`,
  rows: cyphers.map(({ name, description }, index) => ({
    min: index + 1,
    max: index + 1,
    result: name,
    description,
  })),
});

